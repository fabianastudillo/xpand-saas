// Generates the TypeScript types for contracts/api into src/generated.
//   node scripts/generate.js          writes src/generated (after changing a schema)
//   node scripts/generate.js --check  regenerates into a temporary directory and fails if it differs from src/generated
import { compileFromFile } from "json-schema-to-typescript";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const PACKAGE_DIR = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CONTRACT_DIR = resolve(PACKAGE_DIR, "../../contracts/api");
const OUTPUT_DIR = join(PACKAGE_DIR, "src", "generated");
const SCHEMA_SUFFIX = ".schema.json";
const BANNER =
  "/* Generated by packages/api/scripts/generate.js from contracts/api. Do not edit by hand. */";

function schemaFiles() {
  return readdirSync(CONTRACT_DIR)
    .filter((name) => name.endsWith(SCHEMA_SUFFIX))
    .sort();
}

async function generateInto(directory) {
  mkdirSync(directory, { recursive: true });
  for (const file of schemaFiles()) {
    const types = await compileFromFile(join(CONTRACT_DIR, file), {
      bannerComment: BANNER,
      cwd: CONTRACT_DIR,
    });
    const name = basename(file, SCHEMA_SUFFIX);
    writeFileSync(join(directory, `${name}.ts`), types);
  }
}

function listGenerated(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory).filter((name) => name.endsWith(".ts")).sort();
}

function differences(expectedDir, actualDir) {
  const esperados = listGenerated(expectedDir);
  const actuales = listGenerated(actualDir);
  const problemas = [];
  for (const name of esperados) {
    if (!actuales.includes(name)) {
      problemas.push(`falta ${name}`);
    } else if (!readFileSync(join(expectedDir, name)).equals(readFileSync(join(actualDir, name)))) {
      problemas.push(`difiere ${name}`);
    }
  }
  for (const name of actuales) {
    if (!esperados.includes(name)) problemas.push(`sobra ${name}`);
  }
  return problemas;
}

async function check() {
  const temporal = mkdtempSync(join(tmpdir(), "xpand-api-gen-"));
  try {
    await generateInto(temporal);
    const problemas = differences(temporal, OUTPUT_DIR);
    if (problemas.length === 0) {
      console.log("src/generated coincide con contracts/api.");
      return 0;
    }
    console.error("src/generated no coincide con contracts/api. Ejecuta `pnpm --filter @xpand/api gen`:");
    for (const problema of problemas) console.error(`  - ${problema}`);
    return 1;
  } finally {
    rmSync(temporal, { recursive: true, force: true });
  }
}

async function write() {
  rmSync(OUTPUT_DIR, { recursive: true, force: true });
  await generateInto(OUTPUT_DIR);
  console.log(`Generados tipos en ${OUTPUT_DIR}.`);
  return 0;
}

process.exitCode = process.argv.includes("--check") ? await check() : await write();
